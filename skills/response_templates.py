    def _get_time_of_day(self):
        """Определить время суток"""
        hour = datetime.now().hour
        if hour < 12:
            return "утро"
        elif hour < 16:
            return "день"
        elif hour < 22:
            return "вечер"
        else:
            return "ночь"
    
    def get_response(self, command):
        cmd = command.lower().strip()
        
        # Сначала проверяем время суток
        time_of_day = self._get_time_of_day()
        
        # Если приветствие — учитываем время суток
        if any(w in cmd for w in ["привет", "здравствуй", "добрый"]):
            if "утро" in cmd or time_of_day == "утро":
                key = "утро"
            elif "день" in cmd or time_of_day == "день":
                key = "день"
            elif "вечер" in cmd or time_of_day == "вечер":
                key = "вечер"
            elif "ночь" in cmd or time_of_day == "ночь":
                key = "ночь"
            else:
                key = time_of_day
            return random.choice(self.templates.get(key, self.templates["привет"]))
        
        # Как дела — тоже с учётом времени
        if any(w in cmd for w in ["как дела", "как ты"]):
            return random.choice(self.templates["как дела"])
        
        # Прямое совпадение
        for key, responses in self.templates.items():
            if key in cmd:
                return random.choice(responses)
        
        return None
    
    def add_template(self, trigger, response):
        try:
            templates = {}
            if os.path.exists(self.templates_file):
                with open(self.templates_file, "r", encoding="utf-8") as f:
                    templates = json.load(f)
            
            if trigger not in templates:
                templates[trigger] = []
            templates[trigger].append(response)
            
            with open(self.templates_file, "w", encoding="utf-8") as f:
                json.dump(templates, f, ensure_ascii=False, indent=2)
            
            if trigger in self.templates:
                self.templates[trigger].append(response)
            else:
                self.templates[trigger] = [response]
            
            return True
        except:
            return False
    
    def can_handle(self, command):
        cmd = command.lower().strip()
        # Проверяем время суток + стандартные шаблоны
        time_triggers = ["привет", "здравствуй", "добрый", "как дела"]
        if any(t in cmd for t in time_triggers):
            return True
        return self.get_response(command) is not None
    
    def execute(self, command):
        response = self.get_response(command)
        if response:
            self.speech.speak(response)
            return True
        return False